import json

import httpx
import pytest

from poc.natural_comment import JEV_QUESTIONS, compile_feedback, correct, generate, route_signals, validate_integrated


def scores(**overrides):
    return {name: overrides.get(name, 0.0) for name in JEV_QUESTIONS}


def test_compiler_orders_fixed_rules_and_rejects_unknown_instructions():
    assert compile_feedback(["brand_jump", "tone_mismatch"]) == compile_feedback(["tone_mismatch", "brand_jump"])
    with pytest.raises(ValueError):
        compile_feedback(["instruction generated by a model"])
    with pytest.raises(ValueError):
        compile_feedback(["brand_jump", "brand_jump"])


def test_diagnosis_routes_factual_risks_to_review_before_rewriting():
    flagged = scores(scene_error=.4, brand_jump=.8)
    assert route_signals(flagged)["action"] == "review_facts"
    assert route_signals(scores(false_brand_review=.4))["action"] == "review_facts"
    assert route_signals(scores(brand_jump=.4))["action"] == "review_signal"
    assert route_signals(scores(brand_jump=.4))["review_signals"] == ["brand_jump"]
    assert route_signals(scores(brand_jump=.8))["selected"] == ["brand_jump"]
    assert route_signals(scores(brand_jump=.4), errors=["길이"])["action"] == "review_constraints"
    with pytest.raises(ValueError):
        route_signals(scores(brand_jump=True))


def test_integrated_generation_accepts_a_closing_sentence_after_the_brand():
    seen = {}
    comment = "도착하면 전화해라는 말이 마음에 남네. 나도 이별 후 연락 습관이 오래 갔거든. 운명원 사주 잘 본다던데 나도 볼까. 인연 참 어렵다."

    def handler(request):
        seen.update(json.loads(request.content))
        return httpx.Response(200, json={"model": "gemini-4-hydrogen", "output": [{"content": [{"type": "output_text", "text": json.dumps({"action": "draft", "comment": comment, "reason": ""}, ensure_ascii=False)}]}]})

    case = {"scene": "도착하면 전화해 이럴 뻔했다니까", "persona": "이별 뒤 연락 습관을 떠올리는 가상 시청자", "reference_comments": ["생각나는 일이 많네요"]}
    with httpx.Client(transport=httpx.MockTransport(handler)) as client:
        result = generate(case, client, base_url="http://local.test/v1", model="google-vertex/gemini-4-hydrogen")
    assert result["comment"] == comment
    assert result["errors"] == []
    assert seen["model"] == "google-vertex/gemini-4-hydrogen"
    assert json.loads(seen["input"][1]["content"])["persona"] == case["persona"]


def test_brand_and_fortune_are_both_required_near_the_end():
    draft = "도착하면 전화해라는 말을 들으니 사주 생각이 나요. 그 장면이 유독 마음에 남네요. 운명원도 찾아보고 싶어요. 인연은 참 어렵네요."
    assert any("끝부분" in error for error in validate_integrated(draft))


def test_keep_decision_preserves_the_existing_comment():
    original = "다시 만나는 거지 묻는 장면은 좀 답답하네. 나도 예전 일 생각남. 운명원 연애 사주 잘 본다던데 나도 보고 싶다."

    def handler(request):
        return httpx.Response(200, json={"output": [{"content": [{"type": "output_text", "text": json.dumps({"decision": "keep", "comment": "changed", "reason": ""})}]}]})

    with httpx.Client(transport=httpx.MockTransport(handler)) as client:
        result = correct({}, original, ["brand_jump"], [], client, base_url="http://local.test/v1", model="test-model")
    assert result["comment"] == original
    assert result["errors"] == []
